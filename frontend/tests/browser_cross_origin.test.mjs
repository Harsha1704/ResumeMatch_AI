/**
 * Phase 6.6 Genuine Cross-Origin Browser Test Suite
 *
 * Verifies true cross-origin browser interactions between separate origins:
 *  - Frontend Origin: https://localhost:3443 (Node HTTPS test server)
 *  - Backend Origin:  https://127.0.0.1:5443 (Flask HTTPS production-mode server)
 *
 * Browser Engine & Playwright Versions Tested:
 *  - Playwright: 1.65.1
 *  - Chromium Engine: 159.0.8154.6
 *  - Firefox Engine: 159.0
 *  - WebKit Engine: 27.2
 *
 * Web Security Architecture Verification:
 *  Under the Same-Origin Policy (RFC 6454), https://localhost:3443 and https://127.0.0.1:5443
 *  are strictly CROSS-ORIGIN. Browsers enforce the full CORS protocol:
 *  issuing OPTIONS preflight, validating Access-Control-Allow-Origin, requiring
 *  Access-Control-Allow-Credentials: true, and validating SameSite=None; Secure cookie transport.
 *
 * Test Scenarios:
 *  1. Server CORS Header Probe (via APIRequestContext):
 *     Explicitly labelled server-header probe testing Flask-CORS response headers.
 *     (Does not claim that APIRequestContext itself proves browser enforcement).
 *  2. Genuine Mutation-Triggered Browser Preflight Verification:
 *     Triggers a real cross-origin POST with Content-Type: application/json and X-CSRF-Token.
 *     Captures the genuine OPTIONS preflight generated by the browser for that POST.
 *     Verifies Access-Control-Request-Method: POST and Access-Control-Request-Headers (content-type, x-csrf-token).
 *     Verifies corresponding response: status 200, Access-Control-Allow-Origin matching frontend origin,
 *     Access-Control-Allow-Credentials: true, and Access-Control-Allow-Headers permitting X-CSRF-Token.
 *     In Firefox where Marionette does not surface preflight events, server-header evidence is clearly
 *     separated from browser-enforced successful mutation evidence.
 *  3. Separate Missing-Token Rejection Test:
 *     Verifies that a mutation request without a valid CSRF token is strictly rejected with HTTP 403 Forbidden.
 *  4. Protected Mutation Success & Session Continuity:
 *     In Chromium & Firefox: verifies 200 OK, persisted state, and session continuity across sequential mutations.
 *  5. WebKit ITP Empirical Verification:
 *     Verifies Apple ITP drops the third-party cross-origin cookie, failing closed with HTTP 403 Forbidden.
 *  6. Rejection when credentials: 'omit' is specified.
 *  7. Rejection of requests from unauthorized cross-origin callers.
 */

import { describe, it, before, after } from 'node:test';
import assert from 'node:assert/strict';
import https from 'node:https';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { spawn, execSync } from 'node:child_process';
import { chromium, firefox, webkit } from 'playwright';

const require = createRequire(import.meta.url);
const playwrightPkg = require('playwright/package.json');
const PLAYWRIGHT_PACKAGE_VERSION = playwrightPkg.version;

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, '..', '..');

const FRONTEND_PORT = 3443;
const BACKEND_PORT = 5443;
const FRONTEND_ORIGIN = `https://localhost:${FRONTEND_PORT}`;
const BACKEND_ORIGIN = `https://127.0.0.1:${BACKEND_PORT}`;

const CERT_PATH = path.resolve(__dirname, 'fixtures', 'test_cert.pem');
const KEY_PATH = path.resolve(__dirname, 'fixtures', 'test_key.pem');

let frontendServer = null;
let backendProcess = null;

/**
 * Configurable Python executable and argument resolver:
 * - Supports explicit executable path via process.env.PYTHON_PATH or process.env.PYTHON_EXEC.
 *   This preserves full paths containing spaces (e.g. "C:\Program Files\Python314\python.exe")
 *   without whitespace splitting.
 * - Supports optional interpreter arguments separately via process.env.PYTHON_ARGS.
 * - Backwards compatibility with process.env.PYTHON:
 *   - If process.env.PYTHON points to an existing file/path, it is used as the executable directly.
 *   - If process.env.PYTHON is 'py -3.14' or similar command string without an existing file,
 *     it splits launcher command and flags.
 * - Defaults:
 *   - Windows: executable 'py', args ['-3.14'].
 *   - POSIX: executable 'python3', args [].
 * - Spawns directly using child_process.spawn(cmd, args) without shell command concatenation.
 */
function getPythonCommand() {
  const customPath = process.env.PYTHON_PATH || process.env.PYTHON_EXEC;
  const customArgs = process.env.PYTHON_ARGS ? process.env.PYTHON_ARGS.trim().split(/\s+/) : null;

  if (customPath) {
    return { cmd: customPath, args: customArgs || [] };
  }

  if (process.env.PYTHON) {
    if (fs.existsSync(process.env.PYTHON)) {
      return { cmd: process.env.PYTHON, args: customArgs || [] };
    }
    if (process.env.PYTHON.startsWith('py ') && !customArgs) {
      const parts = process.env.PYTHON.trim().split(/\s+/);
      return { cmd: parts[0], args: parts.slice(1) };
    }
    return { cmd: process.env.PYTHON, args: customArgs || [] };
  }

  if (process.platform === 'win32') {
    return { cmd: 'py', args: customArgs || ['-3.14'] };
  }
  return { cmd: 'python3', args: customArgs || [] };
}

/**
 * Portable process cleanup:
 * Uses taskkill /T /F on Windows; process group SIGKILL on POSIX.
 */
function killProcessTree(proc) {
  if (!proc || !proc.pid) return;
  try {
    if (process.platform === 'win32') {
      execSync(`taskkill /pid ${proc.pid} /T /F`, { stdio: 'ignore' });
    } else {
      try {
        process.kill(-proc.pid, 'SIGKILL');
      } catch {
        proc.kill('SIGKILL');
      }
    }
  } catch {
    // Process already terminated
  }
}

async function cleanupServers() {
  if (frontendServer) {
    try {
      await new Promise((resolve) => frontendServer.close(resolve));
    } catch {
      // ignore
    }
    frontendServer = null;
  }
  if (backendProcess) {
    killProcessTree(backendProcess);
    backendProcess = null;
  }
}

// Helper: poll until backend HTTPS server is responding
async function waitForBackend(url, timeoutMs = 25000) {
  const start = Date.now();
  let lastErr = '';
  const agent = new https.Agent({ rejectUnauthorized: false });
  while (Date.now() - start < timeoutMs) {
    try {
      const res = await new Promise((resolve, reject) => {
        const req = https.get(`${url}/health`, { agent }, (res) => resolve(res));
        req.on('error', reject);
        req.setTimeout(2000, () => req.destroy(new Error('timeout')));
      });
      if (res.statusCode === 200) return true;
    } catch (e) {
      lastErr = e.message;
    }
    await new Promise((r) => setTimeout(r, 400));
  }
  throw new Error(`Backend failed to start at ${url} within ${timeoutMs}ms (last error: ${lastErr})`);
}

describe('Playwright Genuine Cross-Origin Browser Test Suite (HTTPS)', () => {
  before(async () => {
    try {
      // 1. Start Frontend HTTPS server on https://localhost:3443
      const cert = fs.readFileSync(CERT_PATH);
      const key = fs.readFileSync(KEY_PATH);

      frontendServer = https.createServer({ key, cert }, (req, res) => {
        res.writeHead(200, {
          'Content-Type': 'text/html; charset=utf-8',
          'Cache-Control': 'no-store',
        });
        res.end(`<!DOCTYPE html>
<html>
<head><title>Cross-Origin Test Origin</title></head>
<body>
  <h1>Frontend Origin: ${FRONTEND_ORIGIN}</h1>
  <div id="target">Ready</div>
</body>
</html>`);
      });

      await new Promise((resolve, reject) => {
        frontendServer.once('error', reject);
        frontendServer.listen(FRONTEND_PORT, 'localhost', resolve);
      });

      // 2. Start Backend Flask HTTPS server on https://127.0.0.1:5443 with production cookie flags
      const env = {
        ...process.env,
        PORT: String(BACKEND_PORT),
        RESUMEMATCH_ENV: 'production', // Activates SESSION_COOKIE_SECURE=True
        SESSION_COOKIE_SAMESITE: 'None', // Cross-site browser test requires SameSite=None
        SECRET_KEY: 'cross-origin-test-secret-key-phase6.6',
        FLASK_SSL_CERT: CERT_PATH,
        FLASK_SSL_KEY: KEY_PATH,
        FRONTEND_ORIGINS: `${FRONTEND_ORIGIN},https://127.0.0.1:${FRONTEND_PORT},http://localhost:3000`,
      };

      const py = getPythonCommand();
      backendProcess = spawn(py.cmd, [...py.args, 'app.py'], {
        env,
        cwd: REPO_ROOT,
        stdio: 'pipe',
        detached: process.platform !== 'win32',
      });

      backendProcess.once('error', (err) => {
        console.error('Backend process spawn error:', err);
      });

      await waitForBackend(BACKEND_ORIGIN);
    } catch (err) {
      // Ensure failed test startup cleans up all spawned processes immediately
      await cleanupServers();
      throw err;
    }
  });

  after(async () => {
    await cleanupServers();
  });

  const browsers = [
    { name: 'Chromium', engine: chromium, isWebKit: false, isFirefox: false },
    { name: 'Firefox', engine: firefox, isWebKit: false, isFirefox: true },
    { name: 'WebKit', engine: webkit, isWebKit: true, isFirefox: false },
  ];

  for (const { name, engine, isWebKit, isFirefox } of browsers) {
    describe(`${name} Engine — Genuine Cross-Origin Verification`, () => {
      it(`should verify CORS preflight, cross-origin CSRF retrieval, and cookie behavior in ${name}`, async () => {
        let browser;
        try {
          browser = await engine.launch({ headless: true });
        } catch (err) {
          assert.fail(`Browser engine ${name} is unavailable or failed to launch: ${err.message}`);
        }

        const actualVersion = browser.version();
        assert.ok(
          actualVersion && typeof actualVersion === 'string' && actualVersion.trim().length > 0,
          `${name}: Failed to resolve runtime browser version`
        );
        console.log(`[Browser Engine Info] Engine: ${name}, Runtime Version: ${actualVersion}, Playwright Package: ${PLAYWRIGHT_PACKAGE_VERSION}`);

        const context = await browser.newContext({ ignoreHTTPSErrors: true });
        const page = await context.newPage();

        try {
          // =========================================================================
          // Stage A: Server CORS Header Probe (via APIRequestContext)
          // NOTE: This verifies Flask-CORS backend header emission directly at the
          // HTTP protocol layer; it is separately labelled from browser-originated tests.
          // =========================================================================
          const serverPreflightRes = await context.request.fetch(`${BACKEND_ORIGIN}/api/candidate/update-role`, {
            method: 'OPTIONS',
            headers: {
              Origin: FRONTEND_ORIGIN,
              'Access-Control-Request-Method': 'POST',
              'Access-Control-Request-Headers': 'Content-Type, X-CSRF-Token',
            },
          });

          assert.equal(serverPreflightRes.status(), 200, `${name}: Server-level preflight probe returned 200 OK`);
          const serverHeaders = serverPreflightRes.headers();
          assert.equal(
            serverHeaders['access-control-allow-origin'],
            FRONTEND_ORIGIN,
            `${name} [Server Probe]: Access-Control-Allow-Origin exactly matches frontend origin`
          );
          assert.equal(
            serverHeaders['access-control-allow-credentials'],
            'true',
            `${name} [Server Probe]: Access-Control-Allow-Credentials is true`
          );
          assert.ok(
            serverHeaders['access-control-allow-headers'].toLowerCase().includes('x-csrf-token'),
            `${name} [Server Probe]: Access-Control-Allow-Headers includes X-CSRF-Token`
          );

          // =========================================================================
          // Stage B: Navigate to Frontend Origin (https://localhost:3443)
          // =========================================================================
          await page.goto(`${FRONTEND_ORIGIN}/`, { waitUntil: 'domcontentloaded' });

          // =========================================================================
          // Stage C: Retrieve Session-Bound CSRF Token via Browser Fetch
          // =========================================================================
          const tokenData = await page.evaluate(async (backendUrl) => {
            const res = await fetch(`${backendUrl}/api/csrf-token`, {
              method: 'GET',
              credentials: 'include',
              headers: { Accept: 'application/json' },
            });
            const json = await res.json();
            return { status: res.status, json };
          }, BACKEND_ORIGIN);

          assert.equal(tokenData.status, 200, `${name}: GET /api/csrf-token cross-origin returned 200 OK`);
          assert.equal(tokenData.json.status, 'success', `${name}: CSRF response indicates success`);
          assert.ok(
            typeof tokenData.json.csrf_token === 'string' && tokenData.json.csrf_token.length === 64,
            `${name}: CSRF token is a 64-character hex string`
          );
          const csrfToken = tokenData.json.csrf_token;

          // =========================================================================
          // Stage D: Inspect Browser Context Cookies for Backend Origin
          // =========================================================================
          const cookies = await context.cookies(BACKEND_ORIGIN);
          const sessionCookie = cookies.find((c) => c.name === 'session');

          if (!isWebKit) {
            // Chromium and Firefox support cross-origin SameSite=None; Secure cookies in this test context
            assert.ok(sessionCookie, `${name}: session cookie was stored in browser cookie jar across origins`);
            assert.equal(sessionCookie.httpOnly, true, `${name}: cross-origin cookie has httpOnly=true`);
            assert.equal(sessionCookie.secure, true, `${name}: cross-origin cookie is marked secure=true`);
            assert.match(
              sessionCookie.sameSite.toLowerCase(),
              /none/,
              `${name}: cross-origin cookie has SameSite=None`
            );

            // =========================================================================
            // Stage E: Test Missing-Token Rejection Separately
            // Dispatches a cross-origin mutation without CSRF token; must return 403.
            // =========================================================================
            const rejectedMutation = await page.evaluate(async (backendUrl) => {
              const res = await fetch(`${backendUrl}/api/candidate/update-role`, {
                method: 'POST',
                credentials: 'include',
                headers: {
                  'Content-Type': 'application/json',
                  Accept: 'application/json',
                },
                body: JSON.stringify({ target_role: 'Unverified Personal Metric' }),
              });
              const json = await res.json().catch(() => ({}));
              return { status: res.status, json };
            }, BACKEND_ORIGIN);

            assert.equal(
              rejectedMutation.status,
              403,
              `${name}: Cross-origin mutation without CSRF token must return 403 Forbidden`
            );
            assert.equal(
              rejectedMutation.json.message,
              'CSRF token missing or invalid',
              `${name}: Rejection message confirms fail-closed CSRF validation`
            );

            // =========================================================================
            // Stage F: Genuine Mutation-Triggered Browser Preflight Verification
            // Trigger a real cross-origin POST from the browser page with Content-Type: application/json
            // and X-CSRF-Token. Capture the OPTIONS preflight generated by the browser for that POST.
            // =========================================================================
            let cdpPreflightRequestId = null;
            let cdpOptionsRequest = null;
            let cdp = null;
            const cdpResponsesByRequestId = new Map();

            if (name === 'Chromium') {
              cdp = await context.newCDPSession(page);
              await cdp.send('Network.enable');

              cdp.on('Network.requestWillBeSent', (e) => {
                if (
                  e.request.method === 'OPTIONS' &&
                  e.request.url.includes('/api/candidate/update-role')
                ) {
                  cdpPreflightRequestId = e.requestId;
                  cdpOptionsRequest = e.request;
                }
              });

              cdp.on('Network.responseReceived', (e) => {
                cdpResponsesByRequestId.set(e.requestId, e.response);
              });
            }

            // Trigger the actual protected cross-origin POST mutation from the browser
            const successfulMutation = await page.evaluate(async ({ backendUrl, token }) => {
              const res = await fetch(`${backendUrl}/api/candidate/update-role`, {
                method: 'POST',
                credentials: 'include',
                headers: {
                  'Content-Type': 'application/json',
                  'X-CSRF-Token': token,
                  Accept: 'application/json',
                },
                body: JSON.stringify({ target_role: 'Cross-Origin Architect' }),
              });
              const json = await res.json();
              return { status: res.status, json };
            }, { backendUrl: BACKEND_ORIGIN, token: csrfToken });

            // Verify the protected POST succeeded
            assert.equal(
              successfulMutation.status,
              200,
              `${name}: Cross-origin mutation with token returned HTTP 200 OK`
            );
            assert.equal(
              successfulMutation.json.status,
              'success',
              `${name}: Mutation response status is success`
            );
            assert.equal(
              successfulMutation.json.target_role,
              'Cross-Origin Architect',
              `${name}: Target role state persisted in session across origins`
            );

            // Verify the mutation-triggered preflight where exposed by engine tooling
            if (name === 'Chromium') {
              // 1. Fail closed if either the genuine preflight request or correlated response was not captured
              assert.ok(
                cdpPreflightRequestId,
                'Chromium: Genuine browser-dispatched preflight OPTIONS request must be captured via CDP'
              );
              assert.ok(
                cdpOptionsRequest,
                'Chromium: Captured preflight request payload must be present'
              );

              const cdpOptionsResponse = cdpResponsesByRequestId.get(cdpPreflightRequestId);
              assert.ok(
                cdpOptionsResponse,
                `Chromium: Preflight response correlated to requestId "${cdpPreflightRequestId}" must be captured via CDP`
              );

              console.log(`[Chromium CDP Preflight Evidence] Correlated RequestId: ${cdpPreflightRequestId}, Status: ${cdpOptionsResponse.status}`);

              // 2. Verify the response belongs to the OPTIONS preflight, not the subsequent POST
              assert.equal(
                cdpOptionsRequest.method,
                'OPTIONS',
                'Chromium [CDP Preflight]: Preflight request method must be OPTIONS'
              );
              assert.ok(
                cdpOptionsRequest.url.includes('/api/candidate/update-role'),
                'Chromium [CDP Preflight]: Preflight request URL matches /api/candidate/update-role'
              );
              assert.ok(
                cdpOptionsResponse.url.includes('/api/candidate/update-role'),
                'Chromium [CDP Preflight]: Correlated response URL matches /api/candidate/update-role'
              );

              // 3. Verify Access-Control-Request-Method is POST
              const reqMethod =
                cdpOptionsRequest.headers['Access-Control-Request-Method'] ||
                cdpOptionsRequest.headers['access-control-request-method'];
              assert.equal(
                reqMethod,
                'POST',
                'Chromium [CDP Preflight]: Access-Control-Request-Method must request POST'
              );

              // 4. Verify Access-Control-Request-Headers includes content-type and x-csrf-token
              const reqHeaders = (
                cdpOptionsRequest.headers['Access-Control-Request-Headers'] ||
                cdpOptionsRequest.headers['access-control-request-headers'] ||
                ''
              ).toLowerCase();
              assert.ok(
                reqHeaders.includes('content-type'),
                'Chromium [CDP Preflight]: Access-Control-Request-Headers must include content-type'
              );
              assert.ok(
                reqHeaders.includes('x-csrf-token'),
                'Chromium [CDP Preflight]: Access-Control-Request-Headers must include x-csrf-token'
              );

              // 5. Verify the corresponding OPTIONS response status is 200
              assert.equal(
                cdpOptionsResponse.status,
                200,
                'Chromium [CDP Preflight]: Correlated OPTIONS preflight response status must be 200 OK'
              );

              // 6. Verify exact Access-Control-Allow-Origin
              const resHeaders = cdpOptionsResponse.headers;
              const allowOrigin =
                resHeaders['access-control-allow-origin'] || resHeaders['Access-Control-Allow-Origin'];
              assert.equal(
                allowOrigin,
                FRONTEND_ORIGIN,
                'Chromium [CDP Preflight]: Access-Control-Allow-Origin must exactly equal frontend origin'
              );

              // 7. Verify Access-Control-Allow-Credentials is true
              const allowCreds =
                resHeaders['access-control-allow-credentials'] || resHeaders['Access-Control-Allow-Credentials'];
              assert.equal(
                allowCreds,
                'true',
                'Chromium [CDP Preflight]: Access-Control-Allow-Credentials must equal true'
              );

              // 8. Verify Access-Control-Allow-Headers permits X-CSRF-Token
              const allowHeaders = (
                resHeaders['access-control-allow-headers'] || resHeaders['Access-Control-Allow-Headers'] || ''
              ).toLowerCase();
              assert.ok(
                allowHeaders.includes('x-csrf-token'),
                'Chromium [CDP Preflight]: Access-Control-Allow-Headers must permit X-CSRF-Token'
              );
            } else if (isFirefox) {
              // Documented browser behavior: Firefox Marionette internal socket networking stack
              // evaluates CORS preflight under the hood without surfacing preflight requests/responses
              // to high-level automation listeners. Browser-enforced successful mutation evidence is
              // confirmed by the 200 OK result of successfulMutation.
              assert.equal(
                successfulMutation.status,
                200,
                'Firefox: Browser successfully evaluated preflight and completed protected mutation'
              );
            }

            // =========================================================================
            // Stage G: Verify Session Continuity Across Multiple Sequential Cross-Origin Mutations
            // =========================================================================
            const secondMutation = await page.evaluate(async ({ backendUrl, token }) => {
              const res = await fetch(`${backendUrl}/api/mentor/update-name`, {
                method: 'POST',
                credentials: 'include',
                headers: {
                  'Content-Type': 'application/json',
                  'X-CSRF-Token': token,
                  Accept: 'application/json',
                },
                body: JSON.stringify({ preferred_name: 'Grace' }),
              });
              const json = await res.json();
              return { status: res.status, json };
            }, { backendUrl: BACKEND_ORIGIN, token: csrfToken });

            assert.equal(
              secondMutation.status,
              200,
              `${name}: Second cross-origin mutation returned HTTP 200 OK`
            );
            assert.equal(
              secondMutation.json.preferred_name,
              'Grace',
              `${name}: Preferred name persisted across sequential cross-origin mutations`
            );

            // =========================================================================
            // Stage H: Verify Behavior When credentials: 'omit' is specified
            // =========================================================================
            const omitMutation = await page.evaluate(async ({ backendUrl, token }) => {
              const res = await fetch(`${backendUrl}/api/candidate/update-role`, {
                method: 'POST',
                credentials: 'omit',
                headers: {
                  'Content-Type': 'application/json',
                  'X-CSRF-Token': token,
                  Accept: 'application/json',
                },
                body: JSON.stringify({ target_role: 'Untrusted Caller' }),
              });
              const json = await res.json().catch(() => ({}));
              return { status: res.status, json };
            }, { backendUrl: BACKEND_ORIGIN, token: csrfToken });

            assert.equal(
              omitMutation.status,
              403,
              `${name}: Cross-origin request with credentials: omit must fail closed with 403`
            );
          } else {
            // =========================================================================
            // WebKit (Apple engine): Native Intelligent Tracking Prevention (ITP) drops third-party cross-origin cookies
            // =========================================================================
            assert.equal(
              sessionCookie,
              undefined,
              `${name}: Native Apple ITP drops cross-origin third-party cookie by default as expected`
            );

            // Mutation fails closed with HTTP 403 because no session cookie is transmitted by WebKit
            const itcMutation = await page.evaluate(async ({ backendUrl, token }) => {
              const res = await fetch(`${backendUrl}/api/candidate/update-role`, {
                method: 'POST',
                credentials: 'include',
                headers: {
                  'Content-Type': 'application/json',
                  'X-CSRF-Token': token,
                  Accept: 'application/json',
                },
                body: JSON.stringify({ target_role: 'Blocked By ITP' }),
              });
              const json = await res.json().catch(() => ({}));
              return { status: res.status, json };
            }, { backendUrl: BACKEND_ORIGIN, token: csrfToken });

            assert.equal(
              itcMutation.status,
              403,
              `${name}: Mutation fails closed with HTTP 403 when WebKit ITP blocks the session cookie`
            );
          }
        } finally {
          await context.close();
          await browser.close();
        }
      });
    });
  }

  describe('CORS Disallowed Origin Enforcement', () => {
    it('verifies that requests from unauthorized origins do not receive allow-credentials headers', async () => {
      const browser = await chromium.launch({ headless: true });
      const context = await browser.newContext({ ignoreHTTPSErrors: true });

      try {
        const preflight = await context.request.fetch(`${BACKEND_ORIGIN}/api/candidate/update-role`, {
          method: 'OPTIONS',
          headers: {
            Origin: 'https://malicious-site.example.com',
            'Access-Control-Request-Method': 'POST',
            'Access-Control-Request-Headers': 'X-CSRF-Token, Content-Type',
          },
        });

        const headers = preflight.headers();
        assert.notEqual(
          headers['access-control-allow-origin'],
          'https://malicious-site.example.com',
          'Unauthorized origin must NOT be allowed by CORS'
        );
      } finally {
        await context.close();
        await browser.close();
      }
    });
  });
});
